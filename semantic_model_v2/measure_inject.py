from __future__ import annotations

import logging
from dataclasses import dataclass, field

from config import (
    SMB_FOLDER_COUNTS,
    SMB_FOLDER_DERIVED,
    SMB_SKIP_TABLE_NAMES,
    SMB_SKIP_TABLE_PREFIXES,
    SMB_TABLE_STRIP_SUFFIXES,
)

from .plan import MeasureSpec, SchemaPlan, TableSpec

logger = logging.getLogger(__name__)


_SKIP_TABLE_PREFIXES = tuple(SMB_SKIP_TABLE_PREFIXES)
_SKIP_TABLE_NAMES = set(SMB_SKIP_TABLE_NAMES)


_FOLDER_COUNTS = SMB_FOLDER_COUNTS
_FOLDER_DERIVED = SMB_FOLDER_DERIVED


@dataclass
class InjectionReport:

    injected: list[tuple[str, str]] = field(default_factory=list)
    skipped: list[tuple[str, str]] = field(default_factory=list)

    @property
    def count(self) -> int:
        return len(self.injected)

    def summary(self) -> str:
        return f"injected {self.count} measure(s) across {len({h for h, _ in self.injected})} table(s)"


def _is_skippable_table(t: TableSpec) -> bool:
    if t.name in _SKIP_TABLE_NAMES:
        return True
    for p in _SKIP_TABLE_PREFIXES:
        if t.name.startswith(p):
            return True
    return t.kind == "calculated"


def _find_key_column(t: TableSpec) -> str | None:
    for c in t.columns:
        if c.is_key:
            return c.name
    for col in t.columns:
        low = col.name.lower()
        if low.endswith("_id") and low.startswith(t.name.split(".")[-1].lower()):
            return col.name
    for col in t.columns:
        low = col.name.lower()
        if low.endswith("_key"):
            return col.name
    for col in t.columns:
        if col.data_type == "int64":
            return col.name
    return None


def _has_column(t: TableSpec, name: str) -> bool:
    return any(c.name == name for c in t.columns)


def _short_label(table_name: str) -> str:
    bare = table_name.split(".")[-1]
    for prefix in ("fact", "dim", "vw_"):
        if bare.lower().startswith(prefix):
            bare = bare[len(prefix) :]
            break
    low = bare.lower()
    for suffix in SMB_TABLE_STRIP_SUFFIXES:
        if low.endswith(suffix):
            bare = bare[: -len(suffix)]
            break
    parts = [p for p in bare.replace("_", " ").split() if p]
    return " ".join(p.capitalize() for p in parts)


def _plural(label: str) -> str:
    if not label:
        return label
    if label.endswith(("s", "z")):
        return label
    if label.endswith("y") and len(label) > 2 and label[-2] not in "aeiou":
        return label[:-1] + "ies"
    return label + "s"


def _add_measure(
    plan: SchemaPlan,
    report: InjectionReport,
    host_table: str,
    name: str,
    dax: str,
    format_string: str | None = None,
    display_folder: str | None = None,
    intent: str = "",
) -> bool:
    if any(m.name == name for m in plan.measures):
        return False
    norm = "".join(dax.split())
    if any("".join((m.dax or "").split()) == norm for m in plan.measures):
        return False
    plan.measures.append(
        MeasureSpec(
            name=name,
            host_table=host_table,
            intent=intent or "Auto-generated by measure_inject",
            template_id=None,
            format_string=format_string,
            display_folder=display_folder,
            dax=dax,
            auto_injected=True,
        )
    )
    report.injected.append((host_table, name))
    return True


def _inject_count_measures(plan: SchemaPlan, t: TableSpec, report: InjectionReport):
    label = _plural(_short_label(t.name))
    key = _find_key_column(t)

    _add_measure(
        plan,
        report,
        t.name,
        name=f"Total {label}",
        dax=f"COUNTROWS('{t.name}')",
        format_string="#,##0",
        display_folder=_FOLDER_COUNTS,
        intent=f"Total row count of {t.name}",
    )

    if key and t.kind == "fact":
        _add_measure(
            plan,
            report,
            t.name,
            name=f"Distinct {label}",
            dax=f"DISTINCTCOUNT('{t.name}'[{key}])",
            format_string="#,##0",
            display_folder=_FOLDER_COUNTS,
            intent=f"Distinct count of {key} on {t.name}",
        )


def _inject_active_inactive(plan: SchemaPlan, t: TableSpec, report: InjectionReport):
    if not _has_column(t, "is_active"):
        return
    label = _plural(_short_label(t.name))
    _add_measure(
        plan,
        report,
        t.name,
        name=f"Active {label}",
        dax=f"CALCULATE(COUNTROWS('{t.name}'), '{t.name}'[is_active] = TRUE())",
        format_string="#,##0",
        display_folder=_FOLDER_COUNTS,
        intent=f"Count of active rows on {t.name}",
    )
    _add_measure(
        plan,
        report,
        t.name,
        name=f"Inactive {label}",
        dax=f"CALCULATE(COUNTROWS('{t.name}'), '{t.name}'[is_active] = FALSE())",
        format_string="#,##0",
        display_folder=_FOLDER_COUNTS,
        intent=f"Count of inactive rows on {t.name}",
    )


def _inject_duration_measures(plan: SchemaPlan, t: TableSpec, report: InjectionReport):
    pairs = [
        ("started_at", "ended_at"),
        ("start_time", "end_time"),
        ("start_date", "end_date"),
    ]
    label = _short_label(t.name)
    for start_col, end_col in pairs:
        if _has_column(t, start_col) and _has_column(t, end_col):
            _add_measure(
                plan,
                report,
                t.name,
                name=f"Avg {label} Duration (mins)",
                dax=(
                    f"AVERAGEX('{t.name}', "
                    f"DATEDIFF('{t.name}'[{start_col}], '{t.name}'[{end_col}], MINUTE))"
                ),
                format_string="#,##0",
                display_folder=_FOLDER_DERIVED,
                intent=f"Average duration in minutes between {start_col} and {end_col}",
            )
            _add_measure(
                plan,
                report,
                t.name,
                name=f"Total {label} Duration (hrs)",
                dax=(
                    f"SUMX('{t.name}', "
                    f"DIVIDE(DATEDIFF('{t.name}'[{start_col}], '{t.name}'[{end_col}], MINUTE), 60))"
                ),
                format_string="#,##0.0",
                display_folder=_FOLDER_DERIVED,
                intent=f"Total duration in hours summed across {t.name}",
            )
            break


def _inject_numeric_aggregates(plan: SchemaPlan, t: TableSpec, report: InjectionReport):
    label_t = _short_label(t.name)
    key = _find_key_column(t)
    for c in t.columns:
        if c.data_type not in {"int64", "double", "decimal"}:
            continue
        low = c.name.lower()
        if c.is_key or c.name == key:
            continue
        if low.endswith(("_id", "_key")):
            continue
        if low.startswith(("created_", "modified_", "load_", "pipeline_")):
            continue
        if low in {"factor", "duration", "amount", "count", "quantity", "value", "qty"}:
            _add_measure(
                plan,
                report,
                t.name,
                name=f"Avg {label_t} {c.name.title()}",
                dax=f"AVERAGE('{t.name}'[{c.name}])",
                format_string="#,##0.00",
                display_folder=_FOLDER_DERIVED,
                intent=f"Average of {c.name} on {t.name}",
            )
            _add_measure(
                plan,
                report,
                t.name,
                name=f"Total {label_t} {c.name.title()}",
                dax=f"SUM('{t.name}'[{c.name}])",
                format_string="#,##0",
                display_folder=_FOLDER_DERIVED,
                intent=f"Sum of {c.name} on {t.name}",
            )


def inject_standard_measures(plan: SchemaPlan) -> InjectionReport:
    report = InjectionReport()
    for t in plan.tables:
        if _is_skippable_table(t):
            report.skipped.append((t.name, "infrastructure/calc table"))
            continue
        if t.kind == "fact":
            _inject_count_measures(plan, t, report)
        _inject_active_inactive(plan, t, report)
        _inject_duration_measures(plan, t, report)
        _inject_numeric_aggregates(plan, t, report)
    logger.info(f"measure_inject: {report.summary()}")
    return report
